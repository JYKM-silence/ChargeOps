-- ============================================================================
-- ChargeOps 新能源充电桩运营平台 —— V3 权益购买金额快照
-- ============================================================================
-- 目的：让「权益退款」这件事有金额可退。
--
-- ★★ 这个迁移存在的唯一理由，是 member_package 上**没有价格列** ★★
--
--   V1 建的 member_package 是「持有权益」表，它的设计立场是「只快照计费要用到的
--   和用户会看到的」（见 MemberPackage 类注释第二节）—— 名称、总量、折扣、有效期。
--   **价格不在那个清单里**，所以这份权益当初花了多少钱，表里一个字都没有。
--
--   这在只有「买入」一条路径时不是问题（SKU 上就有 price，买完就不需要了）。
--   一旦要退钱，它就成了拦路虎：退款金额必须来自**当时真实付掉的那个数**，
--   而那个数在整个库里没有任何地方记着 —— wallet_transaction 里那条
--   PACKAGE_PURCHASE 流水的 order_id 是 NULL（直购模型没有购买单），
--   member_package.buy_order_id 同样恒为 NULL，两者之间**没有 join 键**。
--   见 WalletTransactionType.PACKAGE_PURCHASE 的 javadoc，那里早已写下这句
--   「要真正解决得加一列」。
--
-- ★★ 为什么是 NULL 而不是拿 charge_package.price 回溯填上 ★★
--
--   那样做会往每一行历史数据里写一个**看起来像事实、其实是今天的售价**的数字。
--   charge_package.price 是可编辑的：管理员把它从 100 改成 80 之后，
--   所有按老价格买过的用户都会被按 80 退款，**而且是静默的**——
--   没有人会报错，车主只会收到一笔比应得少的钱，然后来问客服，
--   而客服在后台看到的每一个数字都是自洽的。
--
--   本仓库已经为同一类问题立过规矩：ChargingOrderSweepJob.STALE_REASON 那段
--   拒绝把「可变的配置」固化成「会被永久写进业务数据的文本」。
--   这里是同一个形状。**宁可让这一列空着、让退款路径拒绝并转人工，
--   也不要编一个金额出来。**
--
--   代价要说清楚：本迁移上线之前卖出去的那批权益**退不了款**，
--   接口会返回「没有购买金额快照，请人工处理」。这是一个**有意的**取舍，
--   不是漏了回溯脚本。真的需要对老数据退款时，人工查当时的售价、
--   手工走管理员调账（ADMIN_ADJUST），那条路径本来就为这种情况准备着，
--   而且它会在流水上留一条带 remark 的人为记录。
--
-- ★ 这里没有 DEFAULT：**NULL 就是它的语义**（「不知道」。见下）。
--   写 DEFAULT 0.00 的话，「建于 V3 之前」和「赠送套餐」会变成同一个值，
--   而这两者的下一步动作完全相反 —— 一个该转人工，一个该直接说「没有可退金额」。
--   0 和 NULL 在这里是两个不同的答案。
--
-- ★ 精度 decimal(12,2)：跟 charge_package.price、charging_order.pay_amount、
--   wallet.balance 一致（V1 第 42 行的三档精度约定：「总额/余额 decimal(12,2)」）。
--   不要改成 (10,2) —— 金额列的精度全库统一，混用只会在某次大额补偿时才暴露。
-- ============================================================================

ALTER TABLE `member_package`
    ADD COLUMN `pay_amount` decimal(12, 2) DEFAULT NULL
        COMMENT '购买时实付金额快照；NULL=本列上线前买的（无法退款），0.00=赠送套餐';

-- ============================================================================
-- 一条配套的索引：让「过期权益落库」的定时任务不必全表扫描
-- ============================================================================
-- 定时任务要跑的是：
--
--   UPDATE member_package SET status = 3
--    WHERE status = 1 AND expire_time <= ? LIMIT ?
--
-- ★ **现有的 idx_mp_member_status_expire (member_id, status, expire_time) 服务不了它。**
--   那条索引最左列是 member_id，而这条语句**没有 member_id** ——
--   MySQL 只能退化成扫全索引（比全表扫描好一点，但仍然是线性的，而且
--   每轮都要扫一遍）。这条语句的判据里选择性最强的恰恰是 status
--   （生效中的权益占绝大多数，要捞的过期权益是极少数），
--   把 status 放最左才能一次定位到那一小段。
--
-- ★ 为什么值得多养一条索引：这个任务会随着表的增长**永远**跑下去，
--   而 member_package 是只增不减的（每次购买一行）。一次全表扫描在
--   开发库的几十行上看不出任何问题，在生产的几十万行上就是每轮一次长查询。
--   ——这正是一个「上线很久之后才会暴露、而那时没人会想到是这里」的形状。
--
-- ★ 代价：购买（INSERT）和每次结算（UPDATE）都要多维护一棵索引。
--   这两条路径本身是低频的（一次充电最多一次结算），可以接受。
--   换掉的是一条随数据量线性劣化的定时查询。
--
-- ★ 不用把 locked_order_id 或 package_type 加进来：这条语句的谓词只有
--   status 和 expire_time 两列，加进来的列既不能当等值列用（会被当成
--   残余过滤），又会让索引变宽、写入变慢。
--   ——「索引列应该来自 WHERE 里真实存在的谓词」，这是 V1 里
--   idx_order_status_create 那条注释的同一条规则。
-- ============================================================================

CREATE INDEX `idx_mp_status_expire` ON `member_package` (`status`, `expire_time`);

-- ============================================================================
-- 顺带：把 wallet_transaction.type 的列注释补上第 8 个取值
-- ============================================================================
-- V1 的注释写的是「1充值 2冻结 3解冻 4扣款 5退款 6套餐购买 7管理员调账」。
-- 本轮加了 PACKAGE_REFUND(8)「套餐退款」，不补的话这句注释就成了一句**错话** ——
-- 而它偏偏是排查资金问题时第一个会被读到的东西（DESC wallet_transaction）。
--
-- ★★ 为什么不直接改 V1 里那一行 ★★
--
--   已应用的迁移永不修改：spring.flyway.validate-on-migrate 会把
--   「有人改了 V1」变成一次**启动失败**，这是正确的取舍（见 V1 文件头）。
--   列注释这种纯文档性质的修正，正确的做法就是在这里再 MODIFY 一次。
--
-- ★ 为什么值得单开一个 PACKAGE_REFUND 而不是复用 ADMIN_ADJUST：
--   两者都是「不由订单流程驱动」的钱，但它们是不同的业务事实 ——
--   一个是**系统性**的（作废一份权益，金额由 member_package.pay_amount 决定，
--   有明确的单据可对），一个是**人为**的（运营决定给谁补多少，没有单据）。
--   对账时把它们混在一个 type 里，就只能靠 remark 的文本去区分，
--   而那正是「钱为什么动了」这个问题的答案不该依赖的东西。
--   MemberPackageStatus.VOIDED 的 javadoc 也早就写了这句期望：
--   「作废的原因由 remark 和资金流水回答」—— 流水得先能回答。
--
-- ★ 这里只改 COMMENT，列类型/可空性逐字保持不变（tinyint NOT NULL）。
--   MySQL 8 对「只改注释」的 MODIFY 是 INSTANT 的，不重建表、不锁业务写入。
-- ============================================================================

ALTER TABLE `wallet_transaction`
    MODIFY COLUMN `type` tinyint NOT NULL
        COMMENT '1充值 2冻结 3解冻 4扣款 5退款 6套餐购买 7管理员调账 8套餐退款';
